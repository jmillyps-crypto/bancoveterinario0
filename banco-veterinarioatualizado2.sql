SELECT p.ID_PACIENTE
	,p.id_tutor
	,p.peso
	,(SELECT t.nome FROM tutor t
	WHERE t.id_tutor = p.id_tutor) AS nome_tutor
FROM paciente p
WHERE p.ID_tutor = (SELECT tu.id_tutor FROM tutor tu
					WHERE tu.nome LIKE 'Rafael%'
					AND tu.id_tutor = p.ID_tutor )
AND p.peso > 5;

