SELECT p.id_agendamento
	,p.id_veterinario
	,p.motivo
	,(SELECT t.nome FROM veterinario t
	WHERE t.id_veterinario = p.id_veterinario) AS nome_veterinario
FROM AGENDAMENTO p
WHERE p.ID_VETERINARIO = (SELECT tu.id_veterinario FROM veterinario tu
					WHERE tu.nome LIKE 'Carlos%'
					AND tu.id_veterinario = p.ID_veterinario )
AND p.motivo = 'Exame de Sangue';


