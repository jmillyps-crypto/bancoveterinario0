		r.dia,
       r.id_paciente
	,(SELECT a.nome
    FROM paciente a
    WHERE a.id_paciente = r.id_paciente) AS nome_paciente,
    ( SELECT a.peso FROM paciente a 
    WHERE a.id_paciente = r.id_paciente) AS nome_peso

FROM AGENDAMENTO r
WHERE r.dia BETWEEN '2025-04-01' AND '2026-06-30';


